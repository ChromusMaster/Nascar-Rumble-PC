def glyph_name(ch):
    u = ord(ch)
    return UV2AGL.get(u, "uni%04X" % u)


def final_path(f, lsb):
    p = f()
    if p is None:
        return None
    p = mv(p, lsb, 0)
    p.simplify(fix_winding=True, keep_starting_points=False, clockwise=False)
    return p


def bounds(p):
    if p is None:
        return None
    bp = BoundsPen(None)
    p.draw(bp)
    return bp.bounds


def collect():
    items = [(".notdef", None, 0, notdef, 50, 50)]
    for ch in ORDER:
        w, lsb, rsb, f = GLYPHS[ch]
        items.append((glyph_name(ch), ord(ch), w, f, lsb, rsb))
    out = []
    for name, uni, w, f, lsb, rsb in items:
        if name == ".notdef":
            w = 440
        p = final_path(f, lsb)
        adv = int(round(lsb + w + rsb))
        out.append((name, uni, p, adv))
    return out


def common_tables(fb, items):
    fb.font.recalcTimestamp = False
    fb.font["head"].created = STAMP
    fb.font["head"].modified = STAMP
    b = [bounds(p) for _, _, p, _ in items if p is not None]
    ymax = max(x[3] for x in b)
    ymin = min(x[1] for x in b)
    fb.setupHorizontalHeader(ascent=HHEA_ASC, descent=HHEA_DSC, lineGap=0)
    fb.setupNameTable({
        "copyright": COPYRIGHT,
        "familyName": FAMILY,
        "styleName": STYLE,
        "uniqueFontIdentifier": "%s;%s" % (PSNAME, VERSION),
        "fullName": "%s %s" % (FAMILY, STYLE),
        "version": "Version %s" % VERSION,
        "psName": PSNAME,
        "licenseDescription": LICENSE,
        "licenseInfoURL": LICENSE_URL,
    })
    fb.setupOS2(
        version=4, usWeightClass=400, usWidthClass=5, fsType=0, achVendID="NONE",
        sTypoAscender=HHEA_ASC, sTypoDescender=HHEA_DSC, sTypoLineGap=0,
        usWinAscent=max(HHEA_ASC, int(math.ceil(ymax))), usWinDescent=max(-HHEA_DSC, int(math.ceil(-ymin))),
        sxHeight=XH, sCapHeight=CAP, fsSelection=0x40 | 0x80, ulUnicodeRange1=0b11,
        ulCodePageRange1=1)
    fb.setupPost(isFixedPitch=0, underlinePosition=-130, underlineThickness=60)


def build_ttf(items):
    fb = FontBuilder(UPM, isTTF=True)
    fb.setupGlyphOrder([n for n, _, _, _ in items])
    fb.setupCharacterMap({u: n for n, u, _, _ in items if u is not None})
    glyf, hmtx = {}, {}
    for name, _, p, adv in items:
        pen = TTGlyphPen(None)
        if p is not None:
            p.draw(Cu2QuPen(pen, 1.0, reverse_direction=True))
        glyf[name] = pen.glyph()
        bb = bounds(p)
        hmtx[name] = (adv, int(math.floor(bb[0])) if bb else 0)
    fb.setupGlyf(glyf)
    fb.setupHorizontalMetrics(hmtx)
    common_tables(fb, items)
    for name, g in fb.font["glyf"].glyphs.items():
        g.recalcBounds(fb.font["glyf"])
        hmtx[name] = (hmtx[name][0], g.xMin if g.numberOfContours else 0)
    fb.setupHorizontalMetrics(hmtx)
    return fb.font


def build_otf(items):
    fb = FontBuilder(UPM, isTTF=False)
    fb.setupGlyphOrder([n for n, _, _, _ in items])
    fb.setupCharacterMap({u: n for n, u, _, _ in items if u is not None})
    cs, hmtx = {}, {}
    for name, _, p, adv in items:
        pen = T2CharStringPen(adv, None)
        if p is not None:
            p.draw(pen)
        cs[name] = pen.getCharString()
        bb = bounds(p)
        hmtx[name] = (adv, int(math.floor(bb[0])) if bb else 0)
    fb.setupCFF(PSNAME, {"FullName": "%s %s" % (FAMILY, STYLE), "FamilyName": FAMILY, "Weight": STYLE,
                         "Notice": COPYRIGHT}, cs, {})
    fb.setupHorizontalMetrics(hmtx)
    common_tables(fb, items)
    return fb.font


def write_c(data, path):
    lines = ['#include "lfont.h"', "", "const unsigned char lt_builtin_font[] = {"]
    for i in range(0, len(data), 16):
        lines.append("    " + ",".join("0x%02x" % b for b in data[i:i + 16]) + ",")
    lines += ["};", "", "const unsigned long lt_builtin_font_size = %dul;" % len(data), ""]
    with open(path, "w", newline="\n") as f:
        f.write("\n".join(lines))


def main():
    root = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
    ap = argparse.ArgumentParser()
    ap.add_argument("--c", default=os.path.join(root, "src", "launcher", "lfont.c"))
    ap.add_argument("--out", default=None)
    a = ap.parse_args()
    items = collect()
    ttf = build_ttf(items)
    tmp = a.c + ".ttf.tmp"
    ttf.save(tmp)
    with open(tmp, "rb") as f:
        data = f.read()
    os.remove(tmp)
    TTFont(__import__("io").BytesIO(data))
    write_c(data, a.c)
    print("%s: %d glyphs, %d bytes" % (a.c, len(items), len(data)))
    if a.out:
        os.makedirs(a.out, exist_ok=True)
        base_name = os.path.join(a.out, PSNAME)
        with open(base_name + ".ttf", "wb") as f:
            f.write(data)
        otf = build_otf(items)
        otf.save(base_name + ".otf")
        for flavor in ("woff", "woff2"):
            t = TTFont(base_name + ".ttf")
            t.flavor = flavor
            try:
                t.save(base_name + "." + flavor)
            except ImportError as e:
                print("skipped %s: %s" % (flavor, e), file=sys.stderr)
        print("wrote %s.{ttf,otf,woff,woff2}" % base_name)


if __name__ == "__main__":
    main()
