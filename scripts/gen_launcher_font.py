def _rad(v):
    return (v, v) if isinstance(v, (int, float)) else tuple(v)


def rr(x0, y0, x1, y1, c=0):
    if isinstance(c, (int, float)):
        c = (c, c, c, c)
    hw, hh = (x1 - x0) / 2, (y1 - y0) / 2
    bl, br, tr, tl = [(min(_rad(v)[0], hw), min(_rad(v)[1], hh)) for v in c]
    p = Path()
    p.moveTo(x0 + bl[0], y0)
    p.lineTo(x1 - br[0], y0)
    if br[0] > 0 and br[1] > 0:
        p.cubicTo(x1 - br[0] * (1 - K), y0, x1, y0 + br[1] * (1 - K), x1, y0 + br[1])
    p.lineTo(x1, y1 - tr[1])
    if tr[0] > 0 and tr[1] > 0:
        p.cubicTo(x1, y1 - tr[1] * (1 - K), x1 - tr[0] * (1 - K), y1, x1 - tr[0], y1)
    p.lineTo(x0 + tl[0], y1)
    if tl[0] > 0 and tl[1] > 0:
        p.cubicTo(x0 + tl[0] * (1 - K), y1, x0, y1 - tl[1] * (1 - K), x0, y1 - tl[1])
    p.lineTo(x0, y0 + bl[1])
    if bl[0] > 0 and bl[1] > 0:
        p.cubicTo(x0, y0 + bl[1] * (1 - K), x0 + bl[0] * (1 - K), y0, x0 + bl[0], y0)
    p.close()
    return p


def rect(x0, y0, x1, y1):
    return rr(x0, y0, x1, y1, 0)


def poly(*pts):
    p = Path()
    p.moveTo(*pts[0])
    for pt in pts[1:]:
        p.lineTo(*pt)
    p.close()
    return p


def U(*ps):
    ps = [p for p in ps if p is not None]
    r = ps[0]
    for p in ps[1:]:
        r = op(r, p, PathOp.UNION)
    return r


def D(a, *bs):
    for b in bs:
        a = op(a, b, PathOp.DIFFERENCE)
    return a


def X(a, b):
    return op(a, b, PathOp.INTERSECTION)


def mv(p, dx, dy=0):
    return p.transform(1, 0, 0, 1, dx, dy)


def scale(p, s, dx=0, dy=0):
    return p.transform(s, 0, 0, s, dx, dy)


def flipx(p, w):
    return p.transform(-1, 0, 0, 1, w, 0)


def flipy(p, h):
    return p.transform(1, 0, 0, -1, 0, h)


def rot180(p, w, h):
    return p.transform(-1, 0, 0, -1, w, h)


def rotate(p, deg, cx, cy):
    a = math.radians(deg)
    c, s = math.cos(a), math.sin(a)
    return p.transform(c, s, -s, c, cx - c * cx + s * cy, cy - s * cx - c * cy)


def legw(dx, dy, th):
    return th * math.hypot(dx, dy) / abs(dy)


def stroke(xb, yb, xt, yt, th=S):
    w = legw(xt - xb, yt - yb, th) / 2
    return poly((xb - w, yb), (xb + w, yb), (xt + w, yt), (xt - w, yt))


def hstroke(xl, yl, xr, yr, th=T):
    h = th * math.hypot(xr - xl, yr - yl) / abs(xr - xl) / 2
    return poly((xl, yl - h), (xr, yr - h), (xr, yr + h), (xl, yl + h))


def shell(x0, y0, x1, y1, c=0, open="", s=S, t=T):
    if isinstance(c, (int, float)):
        c = (c, c, c, c)
    c = [_rad(v) for v in c]
    ix0 = x0 - 10 if "l" in open else x0 + s
    iy0 = y0 - 10 if "b" in open else y0 + t
    ix1 = x1 + 10 if "r" in open else x1 - s
    iy1 = y1 + 10 if "t" in open else y1 - t
    ic = []
    for (rx, ry), sides in zip(c, ("lb", "rb", "rt", "lt")):
        if rx > 0 and ry > 0 and not set(sides) & set(open):
            ic.append((max(rx - s, rx * 0.3), max(ry - t, ry * 0.3)))
        else:
            ic.append(0)
    return D(rr(x0, y0, x1, y1, c), rr(ix0, iy0, ix1, iy1, ic))


def apex(w, h, a=70, th=S * 1.04):
    cx = w / 2
    wl = legw(cx - a, h, th)
    return U(poly((0, 0), (wl, 0), (cx - a + wl, h), (cx - a, h)),
             poly((w, 0), (w - wl, 0), (cx + a - wl, h), (cx + a, h)))


def zdiag(w, y0, y1, th=S * 1.05):
    wd = th
    for _ in range(6):
        wd = legw(w - wd, y1 - y0, th)
    return poly((0, y0), (wd, y0), (w, y1), (w - wd, y1))


def s_shape(w, h, r, rm, gap=40, s=S, t=T):
    m = h / 2 + 4
    y0u, y1l = m - t / 2, m + t / 2
    upper = D(shell(0, y0u, w, h, (rm, 0, r, r), s=s, t=t), rect(w - s - 5, y0u - 5, w + 5, h - r - gap))
    lower = D(shell(0, 0, w, y1l, (r, r, rm, 0), s=s, t=t), rect(-5, r + gap, s + 5, y1l + 5))
    return U(upper, lower)


